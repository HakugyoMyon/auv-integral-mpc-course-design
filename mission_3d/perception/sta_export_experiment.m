function files=sta_export_experiment(file,outdir)
% Offline reproducibility metadata; NEVER a navigation-map import artifact.
if nargin<2,outdir=fileparts(file);end
if ~isfolder(outdir),mkdir(outdir);end
z=load(file,'staticSpec','scanner','planner','config','report');
spec=z.staticSpec;meta=struct();
meta.sourceArchive=file;meta.exportedAtUTC=char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd HH:mm:ss'));
meta.environment='static_unknown';meta.taskConfiguration=z.config;meta.report=z.report;
meta.sensorConfiguration=z.scanner;meta.finalPlannerConfiguration=z.planner;
meta.launchPrior=spec.launchPrior;
if isfield(spec,'plannerOverrides'),meta.plannerOverrides=spec.plannerOverrides;else,meta.plannerOverrides=struct();end
meta.sceneMetadata=spec;
if isfield(meta.sceneMetadata,'world'),meta.sceneMetadata=rmfield(meta.sceneMetadata,'world');end
historical=struct();deadlineNames={'computeStopPosix','hardDeadlinePosix'};
for k=1:numel(deadlineNames)
 name=deadlineNames{k};if isfield(meta.sceneMetadata,name)
  historical.(name)=meta.sceneMetadata.(name);meta.sceneMetadata=rmfield(meta.sceneMetadata,name);
 end
end
meta.developmentDeadlineHistoricalOnly=historical;
meta.reproductionWallBudgetPolicy='Archived development wall-clock stamps are historical metadata, not runnable deadlines. A reproduction MUST explicitly set a fresh computeStopPosix/hardDeadlinePosix or equivalent current-run wall budget before running. Preserve the simulated mission time horizon separately; do not reuse expired stamps.';
meta.worldGeometryArtifact='world_geometry_offline_only.json';
meta.scope='Offline experiment configuration and historical evidence. Full obstacle geometry is generated by the simulator and used for sensor synthesis and offline auditing only; it is NOT the navigation map and must NOT be provided to the onboard planner. Planner input is observed packet/nav-derived map plus the explicitly declared launch prior. Named function handles are provenance labels, not serialized executable closures.';
geometry=struct('artifactRole','OFFLINE_SIMULATOR_GROUND_TRUTH_ONLY_NOT_A_NAVIGATION_MAP',...
 'world',spec.world,'scope',meta.scope);
if isfield(spec,'kind'),meta.worldKind=spec.kind;elseif isfield(spec,'worldKind'),meta.worldKind=spec.worldKind;end
if isfield(spec,'seed'),meta.worldSeed=spec.seed;elseif isfield(spec,'worldSeed'),meta.worldSeed=spec.worldSeed;end
if ~isfield(meta,'worldSeed')&&isfield(z.config,'execution')&&isfield(z.config.execution,'seed')
 meta.worldSeed=[];meta.executionSeed=z.config.execution.seed;
 meta.worldSeedNote='No explicit scene seed field archived; executionSeed is reported separately and must not be assumed to be the scene-generation seed.';
end
files.configuration=fullfile(outdir,'experiment_configuration.json');writeJson(files.configuration,sanitize(meta));
files.offlineGeometry=fullfile(outdir,'world_geometry_offline_only.json');writeJson(files.offlineGeometry,sanitize(geometry));
end

function y=sanitize(x)
if isa(x,'function_handle'),y=func2str(x);
elseif isstruct(x)
 y=x;names=fieldnames(x);for k=1:numel(x),for j=1:numel(names),y(k).(names{j})=sanitize(x(k).(names{j}));end;end
elseif iscell(x),y=cell(size(x));for k=1:numel(x),y{k}=sanitize(x{k});end
else,y=x;
end
end

function writeJson(file,value)
fid=fopen(file,'w');assert(fid>=0);closer=onCleanup(@()fclose(fid));fprintf(fid,'%s',jsonencode(value,PrettyPrint=true));
end
