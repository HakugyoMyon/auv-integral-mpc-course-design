function nav=sta_nav_contract(xhat,quality,bodyP,attitudeP,time)
% Declared statistical envelope, not a calibrated deterministic safety bound.
nav=struct('positionNED',xhat(1:3),'quaternion',xhat(4:7),...
 'positionErrorBound_m',hypot(quality.radius95,3*sqrt(max(0,bodyP(3,3)))+.05),...
 'attitudeErrorBound_rad',3*sqrt(max(0,trace(attitudeP))),...
 'valid',quality.valid,'time',time);
end
