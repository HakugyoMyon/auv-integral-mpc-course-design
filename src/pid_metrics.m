function m = pid_metrics(run)
t=run.t; post=t>=30; steady=t>=max(0,t(end)-50);
if ~any(post), post=false(size(t)); post(end)=true; end
m=struct('rmseAll',sqrt(mean(run.ey.^2)), ...
 'rmsePost30',sqrt(mean(run.ey(post).^2)), 'peakPost30',max(abs(run.ey(post))), ...
 'steadyBias',mean(run.ey(steady)),'steadyPeak',max(abs(run.ey(steady))), ...
 'maxSpeedErrorSteady',max(abs(run.z(steady,1)-1.5)), ...
 'maxDepthErrorSteady',max(abs(run.z(steady,9)-10)), ...
 'headingRmseDeg',rad2deg(sqrt(mean(run.controlError(:,1).^2))), ...
 'rudderTVrad',sum(abs(diff(run.z(:,13)))), ...
 'maxRudderDeg',max(abs(rad2deg(run.z(:,13)))), ...
 'rudderRegulatorFraction',mean(run.constraintActive(:,1)), ...
 'rudderAmplitudeFraction',mean(run.amplitudeActive(:,1)), ...
 'rudderCommandRateFraction',mean(run.rateActive(:,1)), ...
 'settlingTime',NaN,'finished',strcmp(run.status,'completed'));
holdSamples=round(10/run.C.Ts);
for k=1:numel(t)-holdSamples
 if all(abs(run.ey(k:k+holdSamples))<=1), m.settlingTime=t(k); break; end
end
if numel(t)>1
 m.maxCommandRate=max(abs(diff(run.command)/run.C.Ts),[],1);
 m.maxActualRate=max(abs(diff(run.z(:,13:15))/run.C.Ts),[],1);
else
 m.maxCommandRate=[0 0 0]; m.maxActualRate=[0 0 0];
end
m.nominalPass=m.finished && m.rmsePost30<=1 && m.peakPost30<=2 ...
 && m.maxSpeedErrorSteady<=.15 && m.maxDepthErrorSteady<=.5;
end
