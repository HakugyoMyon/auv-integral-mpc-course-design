function scenarios = current_design_scenarios()
root=fileparts(fileparts(mfilename('fullpath')));
T=readtable(fullfile(root,'docs','design','scenario_matrix.csv'),'TextType','string');
assert(all(T.u_ref_m_s==1.5) && all(T.depth_ref_m==10) && all(T.initial_N_m==0));
scenarios=cell(height(T),1);
for j=1:height(T)
 amp=T.yaw_moment_amplitude_Nm(j);frequency=T.yaw_moment_frequency_rad_s(j);
 scenarios{j}=struct('id',char(T.id(j)),'path',char(T.path(j)),'duration',T.duration_s(j), ...
  'initialError',T.initial_E_m(j),'headingOffset',deg2rad(T.heading_offset_deg(j)), ...
  'radius',50,'current',[T.current_speed_m_s(j);deg2rad(T.current_direction_deg(j));T.current_vertical_m_s(j)], ...
  'kappa',T.kappa_crossflow(j),'momentAmplitude',amp,'momentFrequency',frequency, ...
  'force',@(t) [0;0;0;0;0;amp*sin(frequency*t)], ...
  'rudderMax',deg2rad(T.rudder_max_deg(j)),'rudderRate',deg2rad(T.rudder_rate_deg_s(j)));
end
end
